class IncidentPayload(BaseModel):
    id: str
    title: str
    text: str
    alert_type: str
    hostname: str
    source_ip: str
    tags: list[str]

@app.post("/analyze")
async def analyze_incident(payload: IncidentPayload):
    try:
        session = await session_service.create_session(
            app_name="soc_advisory_app",
            user_id="n8n_orchestrator",
            state={}
        )
        
        prompt_text = (
            f"NEW DATADOG ALERT RECEIVED:\n"
            f"- Event ID: {payload.id}\n"
            f"- Title: {payload.title}\n"
            f"- Alert Type: {payload.alert_type}\n"
            f"- Hostname: {payload.hostname}\n"
            f"- Source IP: {payload.source_ip}\n"
            f"- Details: {payload.text}\n"
            f"- Tags: {', '.join(payload.tags)}\n\n"
            f"Please conduct the investigation, assess risk rating, formulate recommended fixes, and dispatch the alert email to InfoSec."
        )

        content = types.Content(role="user", parts=[types.Part(text=prompt_text)])
        
        agent_response_text = ""
        tool_calls_executed = []

        events = runner.run(
            app_name="soc_advisory_app",
            user_id="n8n_orchestrator",
            session_id=session.session_id,
            new_message=content
        )

        async for event in events:
            if event.content and event.content.parts:
                for part in event.content.parts:
                    if part.text:
                        agent_response_text += part.text
                    if hasattr(part, "function_call") and part.function_call:
                        tool_calls_executed.append(part.function_call.name)

        return {
            "status": "success",
            "session_id": session.session_id,
            "tool_calls_executed": tool_calls_executed,
            "report": agent_response_text
        }

    except Exception as e:
        raise HTTPException(status_code=500, detail=f"ADK Agent execution failed: {str(e)}")

